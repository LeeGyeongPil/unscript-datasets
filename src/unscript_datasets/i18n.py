def resolve_lang(cli_value: str | None = None, env: Mapping[str, str] | None = None) -> str:
    """Pick ``en`` or ``ko``: ``--lang`` > ``UNSCRIPT_DATASETS_LANG`` > LC_ALL > LC_MESSAGES > LANG."""
    env = os.environ if env is None else env
    if cli_value:
        return cli_value if cli_value in LANGS else "en"
    for name in (ENV_VAR, "LC_ALL", "LC_MESSAGES", "LANG"):
        value = env.get(name, "")
        if value:
            return "ko" if value.lower().startswith("ko") else "en"
    return "en"


def t(lang: str, key: str, **values: object) -> str:
    """Look up ``key`` in ``lang`` and fill ``{placeholders}``."""
    text = MESSAGES[lang][key]
    return text.format(**values) if values else text
